// Manipulating an array with the unshift method in JavaScript

let myArray = [2, 3, 4, 5];
myArray.unshift(1);
console.log(myArray); // Output: [1, 2, 3, 4, 5]    

// You can also unshift multiple elements by passing them as arguments to the unshift method

myArray.unshift(-1, 0);
console.log(myArray); // Output: [-1, 0, 1, 2, 3, 4, 5]

// unshift method adds one or more elements to the beginning of an array
//  and returns the new length of the array.






