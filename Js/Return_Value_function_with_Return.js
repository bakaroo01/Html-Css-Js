// Returning Value from a function using return statement

function add(a, b) {
    return a + b; // Return the sum of a and b
}

console.log("The sum of 5 and 10 is: " + add(5, 10)); // Calling the function and logging the returned value


// Another example of a function that returns a value
function multiply(x, y) {
    return x * y; // Return the product of x and y
}

console.log("The product of 4 and 6 is: " + multiply(4, 6)); // Calling the function and logging the returned value