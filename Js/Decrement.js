// Two common ways to decrement a variable in JavaScript.

// The first way to decrement a variable is to use the decrement operator (--).

let myVar = 5;
myVar--;
console.log(myVar); // Output: 4

// The second way is to use the subtraction assignment operator (-=).

let myVar2 = 5;
myVar2 -= 1;
console.log(myVar2); // Output: 4