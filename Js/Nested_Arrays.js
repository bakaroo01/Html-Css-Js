// Nested Arrays

// A nested array is an array that contains other arrays as its elements. 

// You can access the elements of a nested array using multiple indices.    


let nestedArray = [
  [1, 2, 3],
  [4, 5, 6],
  [7, 8, 9]
];


console.log(nestedArray[0][0]); // Output: 1
console.log(nestedArray[1][2]); // Output: 6
console.log(nestedArray[2][1]); // Output: 8