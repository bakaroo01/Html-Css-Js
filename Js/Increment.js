// Two common ways to increment a variable in JavaScript.

// The first way is to use the increment operator (++).
let myVar = 5;
myVar++;
console.log(myVar); // Output: 6

// The second way is to use the addition assignment operator (+=).
let myVar2 = 5;
myVar2 += 1;
console.log(myVar2); // Output: 6
