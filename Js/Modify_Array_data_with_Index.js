// Modifying array data with index 

// You can modify the values in an array by accessing them 

// using their index and assigning a new value.

let numbers = [10, 20, 30, 40, 50];

console.log(numbers); // Output: [10, 20, 30, 40, 50]

// Modifying the value at index 2
numbers[2] = 65;
console.log(numbers); // Output: [10, 20, 65, 40, 50]

// Arrays are mutable, which means you can change their contents without creating a new array.

// unlike strings, which are immutable, arrays can be modified in place.