// Understanding Boolean Values in JavaScript

// Boolean values are either true or false
var isTrue = true;
var isFalse = false;

console.log(isTrue);  // This will log true
console.log(isFalse); // This will log false

// Boolean values are often used in conditional statements
if (isTrue) {
    console.log("The value is true");
} else {
    console.log("The value is false");
}


