// Storing Multiple Values in an Array


let values = [1, 2, 3, 4, 5];
console.log(values);// Output: [1, 2, 3, 4, 5]



// You can also store different types of values in an array
let mixedValues = [1, "two", true, null, { key: "value" }];
console.log(mixedValues); // Output: [1, "two", true, null, { key: "value" }]

// You can access values in an array using their index
console.log(values[0]); // Output: 1
console.log(values[2]); // Output: 3
console.log(mixedValues[1]); // Output: "two"