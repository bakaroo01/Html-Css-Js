// The two common ways to find the remainder of two numbers.

let remainder = 10 % 3;
console.log(remainder); // Output: 1

// The second way to find the remainder of two numbers.
const num1 = 10;
const num2 = 3;
const result = num1 % num2;
console.log("The remainder is: " + result); // Output: The remainder is: 1