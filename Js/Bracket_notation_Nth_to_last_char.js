// Bracket notation Nth to last character

// In JavaScript, you can access the Nth to last character of a string using bracket notation

// and the index of the Nth to last character, which is the length of the string minus N.

let lastName ="Lovelace"
let secondToLast = lastName[lastName.length - 2]
console.log(secondToLast) // Output: "c"

let thirdToLast = lastName[lastName.length - 3]
console.log(thirdToLast) // Output: "a"
